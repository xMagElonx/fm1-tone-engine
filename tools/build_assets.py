"""Build data/factory.js for the FM-1 tone engine.

Two jobs:
  1. VERIFY: rebuild the four factory banks from the packed ground truth and
     prove the result is byte-identical to the published reference bank.
  2. GENERATE: emit data/factory.js (embedded banks + provenance table).

Everything here is checked against ground truth, never against a blog table.
"""
import base64, json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
REF = ROOT / "ref"
OUT = ROOT / "data"

HEADER = bytes([0xF0, 0x43, 0x00, 0x09, 0x20, 0x00])   # DX7 32-voice bulk dump
TERMINATOR = 0xF7
BANK_DATA = 4096          # 32 voices x 128 bytes
TOTAL = 6 + BANK_DATA + 1 + 1   # 4104


def checksum(data: bytes) -> int:
    """Yamaha DX7 checksum: (128 - (sum & 0x7F)) & 0x7F"""
    return (128 - (sum(data) & 0x7F)) & 0x7F


def build_bank(packed: bytes) -> bytes:
    assert len(packed) == BANK_DATA
    return HEADER + packed + bytes([checksum(packed)]) + bytes([TERMINATOR])


def parse_bank(blob: bytes) -> bytes:
    """Return the 4096 parameter bytes, validating header/checksum."""
    if len(blob) != TOTAL:
        raise ValueError(f"expected {TOTAL} bytes, got {len(blob)}")
    if blob[:6] != HEADER:
        raise ValueError(f"bad DX7 bulk header: {blob[:6].hex(' ')}")
    if blob[4103] != TERMINATOR:
        raise ValueError("missing F7 terminator")
    data = blob[6:6 + BANK_DATA]
    if blob[4102] != checksum(data):
        raise ValueError(
            f"checksum mismatch: file 0x{blob[4102]:02x} vs computed 0x{checksum(data):02x}")
    return data


# ------------------------------------------------------------ 1. VERIFY
packed_all = (REF / "packed128.bin").read_bytes()
assert len(packed_all) == 128 * 128, len(packed_all)

banks = [build_bank(packed_all[i * BANK_DATA:(i + 1) * BANK_DATA]) for i in range(4)]

reference = (REF / "bank1.syx").read_bytes()
if banks[0] == reference:
    print("[PASS] rebuilt bank 1 is byte-identical to the published reference bank")
else:
    print("[FAIL] rebuilt bank 1 differs from the reference")
    for i, (a, b) in enumerate(zip(banks[0], reference)):
        if a != b:
            print(f"        first difference at byte {i}: rebuilt 0x{a:02x} vs ref 0x{b:02x}")
            break
    raise SystemExit(1)

roundtrip = parse_bank(banks[0]) == packed_all[:BANK_DATA]
print(f"[{'PASS' if roundtrip else 'FAIL'}] parse(rebuild(x)) == x")
assert roundtrip

names = ["".join(chr(c) if 32 <= c < 127 else "." for c in
                 packed_all[i * 128 + 118:i * 128 + 128]).rstrip()
         for i in range(128)]
print(f"[INFO] {len(names)} voices, first: {names[0]!r}, last: {names[127]!r}")

# ------------------------------------------------- 2. PROVENANCE TABLE
text = (REF / "protocol.md").read_text(encoding="utf-8")
appendix = text.split("## Appendix")[-1]
prov = {}
for line in appendix.splitlines():
    m = re.match(r"^\|\s*(\d+)\s*\|(.+)\|\s*$", line.strip())
    if not m:
        continue
    slot = int(m.group(1))
    cells = [c.strip() for c in m.group(2).split("|")]
    while len(cells) < 4:
        cells.append("")
    prov[slot] = {
        "name": cells[0].strip("`"),
        "source": cells[1].strip("`"),
        "original": cells[2],
        "yamaha": cells[3],
    }
print(f"[INFO] parsed {len(prov)} provenance rows")
assert len(prov) == 128, f"expected 128 provenance rows, got {len(prov)}"

# ------------------------------------------------------------ 3. EMIT
OUT.mkdir(exist_ok=True)
payload = {
    "banks": [base64.b64encode(b).decode() for b in banks],
    "names": names,
    "provenance": [prov[i] for i in range(128)],
    "meta": {
        "source": "github.com/KingParamount/fm1-factory-presets",
        "captured": "2026-09-12",
        "note": "rebuilt from the FM-1's own restore protocol capture",
    },
}
js = "// generated by tools/build_assets.py - do not edit by hand\n"
js += "window.FM1_FACTORY = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n"
(OUT / "factory.js").write_text(js, encoding="utf-8")
print(f"[OK] wrote {OUT / 'factory.js'} ({(OUT / 'factory.js').stat().st_size} bytes)")
